-- ==============================================================================
-- ThaiUNII: Supabase Database Schema & Full-Text Search Configuration
-- รองรับการสืบค้นรหัส FDA UNII, ชื่อเคมี, เลข CAS, ชื่อสามัญ และสมุนไพรไทย
-- ==============================================================================

-- 1. เปิด Extension สำหรับค้นหาข้อความแบบ Fuzzy Trigram (เร็วและยืดหยุ่นมาก)
CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- 2. สร้างตารางหลัก: substances (ข้อมูลสารและรหัสอ้างอิงสากล)
CREATE TABLE IF NOT EXISTS public.substances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unii VARCHAR(10) NOT NULL UNIQUE,
    legacy_unii VARCHAR(10),
    preferred_name TEXT NOT NULL,
    thai_name TEXT,
    cas_rn VARCHAR(50),
    molecular_formula TEXT,
    pubchem_cid VARCHAR(50),
    substance_type VARCHAR(50) DEFAULT 'chemical',
    type_label_th VARCHAR(100),
    inchikey VARCHAR(50),
    smiles TEXT,
    thai_desc TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- สร้าง Index เพื่อให้การค้นหาเร็วระดับ Millisecond
CREATE INDEX IF NOT EXISTS idx_substances_unii ON public.substances (unii);
CREATE INDEX IF NOT EXISTS idx_substances_legacy ON public.substances (legacy_unii);
CREATE INDEX IF NOT EXISTS idx_substances_cas ON public.substances (cas_rn);
CREATE INDEX IF NOT EXISTS idx_substances_type ON public.substances (substance_type);

-- Trigram Index สำหรับค้นหาชื่อภาษาไทยและชื่อเคมีแบบไม่ต้องพิมพ์ตรงเป๊ะ (Autocomplete & Fuzzy)
CREATE INDEX IF NOT EXISTS idx_substances_pref_trgm ON public.substances USING gin (preferred_name gin_trgm_ops);
CREATE INDEX IF NOT EXISTS idx_substances_thai_trgm ON public.substances USING gin (thai_name gin_trgm_ops);

-- 3. สร้างตารางชื่อพ้อง: substance_synonyms (ข้อมูลจากไฟล์ UNII_Names)
CREATE TABLE IF NOT EXISTS public.substance_synonyms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unii VARCHAR(10) NOT NULL REFERENCES public.substances(unii) ON DELETE CASCADE,
    synonym TEXT NOT NULL,
    name_type VARCHAR(20) DEFAULT 'cn' -- of=official, sys=systematic, cn=common, bn=brand
);

CREATE INDEX IF NOT EXISTS idx_synonyms_unii ON public.substance_synonyms (unii);
CREATE INDEX IF NOT EXISTS idx_synonyms_text_trgm ON public.substance_synonyms USING gin (synonym gin_trgm_ops);

-- 4. สร้างตารางประวัติรหัสเดิม: legacy_uniis (ข้อมูลจากไฟล์ Legacy UNIIs)
CREATE TABLE IF NOT EXISTS public.legacy_uniis (
    legacy_unii VARCHAR(10) PRIMARY KEY,
    current_unii VARCHAR(10) NOT NULL,
    preferred_term TEXT
);

CREATE INDEX IF NOT EXISTS idx_legacy_lookup ON public.legacy_uniis (legacy_unii, current_unii);

-- ==============================================================================
-- 5. ตั้งค่าความปลอดภัย Row Level Security (RLS)
-- อนุญาตให้บุคคลทั่วไป (anon) อ่าน/ค้นหาข้อมูลได้ฟรีโดยไม่ต้องล็อกอิน
-- แต่จำกัดสิทธิ์แก้ไข/เพิ่มข้อมูลเฉพาะ Service Role (สคริปต์หลังบ้าน)
-- ==============================================================================
ALTER TABLE public.substances ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.substance_synonyms ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.legacy_uniis ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public read-only access on substances" 
ON public.substances FOR SELECT TO anon, authenticated USING (true);

CREATE POLICY "Allow public read-only access on synonyms" 
ON public.substance_synonyms FOR SELECT TO anon, authenticated USING (true);

CREATE POLICY "Allow public read-only access on legacy_uniis" 
ON public.legacy_uniis FOR SELECT TO anon, authenticated USING (true);

-- ==============================================================================
-- 6. ฟังก์ชันสืบค้นอัจฉริยะ (RPC Search Function) สำหรับเชื่อมต่อกับ Frontend
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.search_thai_unii(
    search_term TEXT DEFAULT '',
    filter_category TEXT DEFAULT 'all',
    only_legacy_flag BOOLEAN DEFAULT FALSE,
    max_results INT DEFAULT 50
)
RETURNS TABLE (
    unii VARCHAR(10),
    legacy_unii VARCHAR(10),
    preferred_name TEXT,
    thai_name TEXT,
    cas_rn VARCHAR(50),
    molecular_formula TEXT,
    pubchem_cid VARCHAR(50),
    substance_type VARCHAR(50),
    type_label_th VARCHAR(100),
    inchikey VARCHAR(50),
    smiles TEXT,
    thai_desc TEXT,
    synonyms TEXT[]
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    clean_term TEXT := TRIM(search_term);
BEGIN
    RETURN QUERY
    SELECT 
        s.unii,
        s.legacy_unii,
        s.preferred_name,
        s.thai_name,
        s.cas_rn,
        s.molecular_formula,
        s.pubchem_cid,
        s.substance_type,
        s.type_label_th,
        s.inchikey,
        s.smiles,
        s.thai_desc,
        COALESCE(ARRAY_AGG(syn.synonym) FILTER (WHERE syn.synonym IS NOT NULL), '{}') AS synonyms
    FROM public.substances s
    LEFT JOIN public.substance_synonyms syn ON s.unii = syn.unii
    WHERE 
        (filter_category = 'all' OR s.substance_type = filter_category)
        AND (NOT only_legacy_flag OR s.legacy_unii IS NOT NULL)
        AND (
            clean_term = ''
            OR s.unii ILIKE clean_term || '%'
            OR s.legacy_unii ILIKE clean_term || '%'
            OR s.cas_rn ILIKE clean_term || '%'
            OR s.preferred_name ILIKE '%' || clean_term || '%'
            OR s.thai_name ILIKE '%' || clean_term || '%'
            OR EXISTS (
                SELECT 1 FROM public.substance_synonyms sub_syn 
                WHERE sub_syn.unii = s.unii AND sub_syn.synonym ILIKE '%' || clean_term || '%'
            )
        )
    GROUP BY s.id, s.unii, s.legacy_unii, s.preferred_name, s.thai_name, s.cas_rn, s.molecular_formula, s.pubchem_cid, s.substance_type, s.type_label_th, s.inchikey, s.smiles, s.thai_desc
    ORDER BY 
        CASE 
            WHEN s.unii = UPPER(clean_term) THEN 1
            WHEN s.preferred_name ILIKE clean_term || '%' THEN 2
            WHEN s.thai_name ILIKE clean_term || '%' THEN 3
            ELSE 4
        END,
        s.preferred_name ASC
    LIMIT max_results;
END;
$$;

